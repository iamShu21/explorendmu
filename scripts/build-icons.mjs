// Subset Flaticon UIcons (regular rounded) to only the icons this site uses.
// Scans src/ for `fi-rr-<name>` classes, keeps those glyphs, and writes
// src/assets/fonts/uicons-rr-subset.woff2 plus src/styles/icons.css.
// The full font is about 385 KB; the subset is a few KB.
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, existsSync } from 'node:fs';
import { join, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = join(root, 'node_modules/@flaticon/flaticon-uicons/css');
const css = readFileSync(join(pkg, 'regular/rounded.css'), 'utf8');
const fontFile = readdirSync(pkg).find((f) => /^uicons-regular-rounded-.*\.woff2$/.test(f));
if (!fontFile) throw new Error('Flaticon regular rounded font not found');

const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const used = new Set();
for (const f of walk(join(root, 'src'))) {
  if (!['.astro', '.js', '.ts', '.json', '.md'].includes(extname(f))) continue;
  for (const m of readFileSync(f, 'utf8').matchAll(/fi-rr-([a-z0-9-]+)/g)) used.add(m[1]);
}

const codes = {};
for (const name of [...used].sort()) {
  const m = css.match(new RegExp(`\\.fi-rr-${name.replace(/[-]/g, '\\-')}:before\\{content:"\\\\([0-9a-f]+)"\\}`));
  if (!m) throw new Error(`Unknown icon fi-rr-${name}`);
  codes[name] = parseInt(m[1], 16);
}

const outFont = join(root, 'src/assets/fonts/uicons-rr-subset.woff2');
const outCss = join(root, 'src/styles/icons.css');
mkdirSync(dirname(outFont), { recursive: true });
const text = Object.values(codes).map((c) => String.fromCodePoint(c)).join('');
const subset = await subsetFont(readFileSync(join(pkg, fontFile)), text, { targetFormat: 'woff2' });

const rules = Object.entries(codes).map(([n, c]) => `.fi-rr-${n}::before{content:"\\${c.toString(16)}"}`).join('\n');
const sheet =
  '/* Generated by scripts/build-icons.mjs from Flaticon UIcons (regular rounded). Do not edit. */\n' +
  '@font-face{font-family:"uicons-rr";src:url("../assets/fonts/uicons-rr-subset.woff2") format("woff2");font-display:block}\n' +
  '[class^="fi-rr-"],[class*=" fi-rr-"]{display:inline-flex;line-height:1}\n' +
  '[class^="fi-rr-"]::before,[class*=" fi-rr-"]::before{font-family:"uicons-rr"!important;font-style:normal;font-weight:400!important;line-height:1;-webkit-font-smoothing:antialiased}\n' +
  rules + '\n';

// Only touch the files when something changed, so the dev server does not reload for nothing.
const same = (file, data) => existsSync(file) && Buffer.compare(readFileSync(file), Buffer.from(data)) === 0;
if (!same(outFont, subset)) writeFileSync(outFont, subset);
if (!same(outCss, sheet)) writeFileSync(outCss, sheet);
console.log(`${Object.keys(codes).length} icons, ${subset.length} bytes`);
