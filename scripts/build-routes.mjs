// Builds src/data/routes.gen.json from src/data/campus-network.json.
//
// What it computes, and how:
//  - metresPerUnit: (sum of the metres recorded in the 60 walk names) / (sum of their path lengths).
//  - walk:   the "Gate 03 to Library" walk as points, with the running distance in metres at every point
//            (path length x metresPerUnit).
//  - routes: for every routed place, the walked route that reaches it from a gate.
//            One walk when the team walked it straight from a gate: "metres" is then the distance the app
//            recorded for that walk (the number in its name). Otherwise the fewest walks chained end to end
//            at the places they share: no distance is given for those, because the app joins walks
//            mid-way at junctions and would take a shorter line.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parsePath, dist, toPath, metresPerUnit, stripMetres, namedMetres, walkEnds } from './lib/network.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const net = JSON.parse(readFileSync(join(root, 'src/data/campus-network.json'), 'utf8'));
const k = metresPerUnit(net);

// The scroll-to-walk route
const walkSrc = net.walks.find((w) => stripMetres(w.name) === 'Gate 03 to Library');
const walkPts = parsePath(walkSrc.d);
let run = 0;
const cum = walkPts.map((p, i) => (i ? (run += dist(walkPts[i - 1], p) * k) : 0));
const walk = {
  name: stripMetres(walkSrc.name),
  recordedMetres: namedMetres(walkSrc.name),
  computedMetres: +run.toFixed(1),
  pts: walkPts,
  cum: cum.map((c) => +c.toFixed(1)),
};

// Place graph: every walk is an edge between the two places it joins, weighted by its recorded metres.
const edges = net.walks.map((w) => { const [a, b] = walkEnds(w.name); return { a, b, m: namedMetres(w.name), pts: parsePath(w.d) }; });
const isGate = (n) => /^Gate \d+$/.test(n);
const gates = net.places.map((p) => p.name).filter(isGate);
const routes = {};
for (const place of net.places.map((p) => p.name).filter((n) => !isGate(n))) {
  let best = null;
  for (const gate of gates) {
    // Dijkstra over places: fewest walks first, then fewest metres.
    const cost = new Map([[gate, [0, 0]]]), prev = new Map(), done = new Set(), queue = [gate];
    const less = (x, y) => x[0] < y[0] || (x[0] === y[0] && x[1] < y[1]);
    while (queue.length) {
      let qi = 0;
      for (let i = 1; i < queue.length; i++) if (less(cost.get(queue[i]), cost.get(queue[qi]))) qi = i;
      const u = queue.splice(qi, 1)[0];
      if (done.has(u)) continue;
      done.add(u);
      for (const e of edges) {
        const v = e.a === u ? e.b : e.b === u ? e.a : null;
        if (!v || (isGate(v) && v !== gate)) continue;
        const c = [cost.get(u)[0] + 1, cost.get(u)[1] + e.m];
        if (!cost.has(v) || less(c, cost.get(v))) { cost.set(v, c); prev.set(v, { from: u, e }); queue.push(v); }
      }
    }
    if (!cost.has(place)) continue;
    const c = cost.get(place);
    if (!best || c[0] < best.c[0] || (c[0] === best.c[0] && c[1] < best.c[1])) best = { gate, c, prev };
  }
  if (!best) continue;
  const legs = [];
  for (let u = place; best.prev.has(u); u = best.prev.get(u).from) {
    const { from, e } = best.prev.get(u);
    legs.unshift(e.a === from ? e.pts : [...e.pts].reverse());
  }
  const pts = legs.flatMap((l, i) => (i ? l.slice(1) : l));
  routes[place] = { from: best.gate, walks: best.c[0], ...(best.c[0] === 1 ? { metres: best.c[1] } : {}), d: toPath(pts) };
}

const out = {
  note: 'Generated by scripts/build-routes.mjs from campus-network.json. Do not edit.',
  metresPerUnit: +k.toFixed(4),
  walk,
  routes,
};
writeFileSync(join(root, 'src/data/routes.gen.json'), JSON.stringify(out) + '\n');
const direct = Object.values(routes).filter((r) => r.walks === 1).length;
console.log(`scale ${k.toFixed(4)} m/unit · ${walk.name}: ${walk.computedMetres} m computed, ${walk.recordedMetres} m recorded · ${Object.keys(routes).length} routes (${direct} single walks, ${Object.keys(routes).length - direct} chained)`);
