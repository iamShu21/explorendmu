"""Subset Flaticon UIcons (regular rounded) to only the icons this site uses.

Scans src/ for `fi-rr-<name>` classes, keeps those glyphs, and writes
public/fonts/uicons-rr-subset.woff2 plus src/styles/icons.css.
The full font is ~385 KB; the subset is a few KB.
"""
import pathlib, re, sys
from fontTools import subset
from fontTools.ttLib import TTFont

root = pathlib.Path(__file__).resolve().parent.parent
pkg = root / 'node_modules/@flaticon/flaticon-uicons/css'
css = (pkg / 'regular/rounded.css').read_text()
font = next(pkg.glob('uicons-regular-rounded-*.woff2'))

used = set()
for f in (root / 'src').rglob('*'):
    if f.suffix in {'.astro', '.js', '.ts', '.json', '.md'}:
        used |= set(re.findall(r'fi-rr-([a-z0-9-]+)', f.read_text(errors='ignore')))

codes = {}
for name in sorted(used):
    m = re.search(r'\.fi-rr-' + re.escape(name) + r':before\{content:"\\([0-9a-f]+)"\}', css)
    if not m:
        sys.exit(f'Unknown icon fi-rr-{name}')
    codes[name] = int(m.group(1), 16)

out_font = root / 'public/fonts/uicons-rr-subset.woff2'
out_font.parent.mkdir(parents=True, exist_ok=True)
opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = []
tt = TTFont(font)
sub = subset.Subsetter(opts); sub.populate(unicodes=list(codes.values())); sub.subset(tt)
tt.flavor = 'woff2'; tt.save(out_font)

rules = '\n'.join(f'.fi-rr-{n}::before{{content:"\\{c:x}"}}' for n, c in codes.items())
(root / 'src/styles/icons.css').write_text(
    '/* Generated by scripts/build_icons.py from Flaticon UIcons (regular rounded). Do not edit. */\n'
    '@font-face{font-family:"uicons-rr";src:url("/fonts/uicons-rr-subset.woff2") format("woff2");font-display:block}\n'
    '[class^="fi-rr-"],[class*=" fi-rr-"]{display:inline-flex;line-height:1}\n'
    '[class^="fi-rr-"]::before,[class*=" fi-rr-"]::before{font-family:"uicons-rr"!important;font-style:normal;font-weight:400!important;line-height:1;-webkit-font-smoothing:antialiased}\n'
    + rules + '\n')
print(f'{len(codes)} icons, {out_font.stat().st_size} bytes')
